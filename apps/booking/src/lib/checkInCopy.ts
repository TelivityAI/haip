export type CheckInLocale = 'en' | 'fr';

export function resolveCheckInLocale(lang = typeof navigator !== 'undefined' ? navigator.language : 'en'): CheckInLocale {
  return lang.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

